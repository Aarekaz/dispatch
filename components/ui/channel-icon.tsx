/** Official brand colors per channel. */
const BRAND_COLORS: Record<Channel, string> = {
  slack: "#611f69",   // Slack aubergine (primary brand)
  whatsapp: "#25D366",
  telegram: "#229ED9",
  discord: "#5865F2",
  email: "currentColor",
  web: "currentColor",
};

type ChannelIconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  /** Channel key (case-insensitive). Unknown keys render `null`. */
  channel: string;
  /** Use `"mono"` to render in currentColor instead of brand colors. */
  variant?: "colored" | "mono";
};

/**
 * Render a channel icon. Defaults to brand-colored; pass
 * `variant="mono"` for monochrome (inherits parent text color).
 */
export function ChannelIcon({
  channel,
  variant = "colored",
  className,
  ...rest
}: ChannelIconProps) {
  const key = channel.toLowerCase() as Channel;
  const paths = ICON_PATHS[key];
  if (!paths) return null;

  const fillColor = variant === "colored"
    ? (BRAND_COLORS[key] ?? "currentColor")
    : "currentColor";

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill={fillColor}
      aria-hidden="true"
      className={cn("size-3 shrink-0", className)}
      {...rest}
    >
      {paths}
    </svg>
  );
}
